// Compile the approved design skins into scoped runtime assets. No design HTML
// or snapshot is shipped with the app; rerun only when the design sources change.
import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
import vm from 'node:vm';
const root = path.resolve(import.meta.dirname, '..');
const design = path.join(root, 'docs/designs/themes-2026-10-17/round-06-current-ui');
const output = path.join(root, 'src/themes');
await fs.mkdir(output, { recursive: true });
const manifest = JSON.parse(await fs.readFile(path.join(design, 'manifest.json'), 'utf8'));
const snapshot = JSON.parse(await fs.readFile(path.join(design, 'source-snapshot.json'), 'utf8'));
const raw = snapshot.css.replace(/@import\s+url\([^;]+;/g, '').replace(/\r\n/g, '\n');
const baseTokens={dark:{},light:{}};
postcss.parse(await fs.readFile(path.join(root,'src/styles.css'),'utf8')).walkRules(rule=>{
  if(rule.selector===':root')rule.walkDecls(decl=>{if(decl.prop.startsWith('--'))baseTokens.dark[decl.prop]=decl.value;});
  if(/^:root\[data-theme=['"]light['"]\]$/.test(rule.selector))rule.walkDecls(decl=>{if(decl.prop.startsWith('--'))baseTokens.light[decl.prop]=decl.value;});
  if(/^\.ring-[0-3]$/.test(rule.selector))rule.walkDecls(decl=>{if(decl.prop==='--ring-color')baseTokens.dark[`--${rule.selector.slice(1)}`]=decl.value;});
});
baseTokens.light={...baseTokens.dark,...baseTokens.light};
await fs.writeFile(path.join(output,'base-tokens.json'),JSON.stringify(baseTokens,null,2)+'\n');
const widgetBuild = await fs.readFile(path.join(design, 'build-widget.mjs'), 'utf8');
const widgets = vm.runInNewContext(`(${widgetBuild.match(/const skins = (\{[\s\S]*?\n\});/)[1]})`);
const catalog = [];
const sheets = ['/* Generated by scripts/prepare-themes.mjs. */'];
for (const candidate of manifest.candidates.filter(t => widgets[t.id])) {
  const id = candidate.id.replace(/^legacy-/, '');
  const html = await fs.readFile(path.join(design, candidate.source), 'utf8');
  const style = html.match(/<style>([\s\S]*?)<\/style>/)[1].replace(/\r\n/g, '\n');
  if (!style.startsWith(raw)) throw Error(`Snapshot mismatch: ${id}`);
  let skin = style.slice(raw.length);
  skin = skin.slice(skin.indexOf('font-variant-numeric:tabular-nums; }') + 'font-variant-numeric:tabular-nums; }'.length);
  skin = skin.slice(0, skin.indexOf('/* Keep the actual four-column'));
  const tree = postcss.parse(skin);
  const tokens = {};
  tree.walkAtRules(rule => { if (['import','font-face','keyframes'].includes(rule.name)) rule.remove(); });
  tree.walkRules(rule => {
    for(let i=0;i<4;i++)if(rule.selectors.includes(`.ring-${i}`))rule.walkDecls(decl=>{if(decl.prop==='--ring-color')tokens[`--ring-${i}`]=decl.value;});
    const cardLayout = /\.overview-grid\s*>\s*\.overview-card(?:\s|$|:nth)/.test(rule.selector) && !/:(?:before|after)/.test(rule.selector);
    if(cardLayout || /\.(overview-head|overview-body|overview-meters)(?:\s|$|,)/.test(rule.selector)) rule.walkDecls(decl=>{
      if(/^(?:padding|margin)(?:-|$)/.test(decl.prop)||['min-height','height','gap'].includes(decl.prop))decl.remove();
    });
    if(rule.selector.includes('.concentric-rings')&&!rule.selector.includes(':before')&&!rule.selector.includes(':after'))rule.walkDecls(decl=>{
      if(['width','height','min-width','max-width','flex','flex-basis','transform'].includes(decl.prop))decl.remove();
    });
    if(rule.selector.includes('.ring-core strong')) rule.walkDecls(decl=>{
      if(decl.prop==='font-size')decl.remove();
      if(decl.prop==='font'){decl.prop='font-family';decl.value=decl.value.replace(/^.*?\d+(?:\.\d+)?px(?:\/[^ ]+)?\s+/,'');}
    });
    // Theme skins decorate the live component tree, never choose its columns.
    if (rule.selector.includes('.overview-grid')) rule.walkDecls(decl => {
      if (['display','grid-template-columns','grid-template-rows','grid-auto-flow','flex','flex-basis','width','max-width','order','gap','align-items'].includes(decl.prop)) decl.remove();
    });
    if (rule.selector.includes(':root')) rule.walkDecls(decl => { if (decl.prop.startsWith('--')) tokens[decl.prop] = decl.value; });
    rule.selectors = rule.selectors.map(selector => {
      const attribute = `[data-theme-id="${id}"]`;
      if (selector.includes(':root')) return selector.replace(/:root(?:\[[^\]]*\])?/g, `:root${attribute}`);
      if (/^(html|body)(?=[\s.:#[]|$)/.test(selector)) return selector.replace(/^(html|body)/, `$1:where(${attribute})`);
      return `:where(html${attribute}) ${selector}`;
    });
  });
  const mode = html.match(/data-theme="([^"]+)"/)[1];
  for(let i=0;i<4;i++)if(!tokens[`--ring-${i}`])tokens[`--ring-${i}`]=baseTokens[mode][`--ring-${i}`];
  const [bg,row,chip,text,label,value,sub,accent,radius,edge,material] = widgets[candidate.id];
  Object.assign(tokens, {'--widget-bg':bg,'--widget-row':row,'--widget-row-border':edge,'--widget-text':text,'--widget-chip':chip,'--widget-chip-label':label,'--widget-chip-value':value,'--widget-chip-sub':sub,'--widget-tag-bg':chip,'--widget-tag-text':value,'--widget-live':accent,'--widget-live-label':label});
  const fallbacks={'--drawer-bg':'var(--surface)','--surface-trans':'var(--surface)','--control-2':'var(--surface-3)','--line-strong':'var(--line)','--hover-border':'var(--ink-soft)','--focus-ring':'color-mix(in srgb,var(--focus-border) 18%,transparent)','--primary-bg':mode==='dark'?'var(--green-deep)':'var(--ink)','--primary-text':mode==='dark'?'var(--bg)':'var(--surface)','--primary-bg-hover':mode==='dark'?'var(--green)':'var(--ink-soft)'};
  for(const [key,value] of Object.entries(fallbacks)) if(!tokens[key]) tokens[key]=value;
  const colorTokens = new Map();
  for (const [key,value] of Object.entries(tokens)) if (/^#[\da-f]{3,8}$/i.test(value) && !colorTokens.has(value.toLowerCase())) colorTokens.set(value.toLowerCase(),key);
  tree.walkDecls(decl => {
    if (!decl.prop.startsWith('--')) decl.value=decl.value.replace(/#[\da-f]{3,8}\b/gi,color=>colorTokens.has(color.toLowerCase())?`var(${colorTokens.get(color.toLowerCase())})`:color);
  });
  const vars = Object.entries(tokens).map(([k,v]) => `${k}:${v}`).join(';');
  const scope = `:root[data-theme-id="${id}"]`;
  const widgetMaterial = {
    flip:'background:linear-gradient(to bottom,transparent 49%,#090e0b90 49% 52%,transparent 52%),var(--widget-row);box-shadow:inset 0 0 0 2px #111914',
    topo:'background:repeating-radial-gradient(ellipse at 100% 0%,transparent 0 12px,#245c501b 13px 14px,transparent 15px 25px),var(--widget-row)',
    grid:'box-shadow:inset -4px 0 var(--widget-live)',
    glow:'box-shadow:inset 0 0 16px color-mix(in srgb,var(--widget-live) 15%,transparent)',
    terminal:'box-shadow:inset 0 0 0 1px #0d130d;font-family:Consolas,monospace',
    paper:'background:repeating-linear-gradient(0deg,transparent 0 5px,#3b2d2010 6px),var(--widget-row)',
    block:'box-shadow:inset 4px 0 var(--widget-live)',
    pop:'box-shadow:inset 0 0 0 1px var(--widget-row-border)',
    ink:'background:radial-gradient(ellipse at 90% 40%,#597d6a1c,transparent 65%),var(--widget-row)',
    acid:'box-shadow:inset 0 0 0 1px var(--widget-live)',
    collage:'box-shadow:inset 0 -2px var(--widget-live)',
    orbital:'border-width:2px',signal:'border-left-width:4px'
  }[material] || '';
  sheets.push(tree.toString(), `${scope}{${vars}}`, `${scope} .widget-row.compact{border-radius:${radius};border:1px solid var(--widget-row-border);${widgetMaterial}}`);
  catalog.push({id,name:candidate.name.replace(' · 现版适配',''),description:candidate.concept,mode,palette:candidate.palette,tokens,group:['pine','porcelain','ocean','sand'].includes(id)?'restrained':'designed'});
}
await fs.writeFile(path.join(output, 'builtins.css'), sheets.join('\n'));
await fs.writeFile(path.join(output, 'catalog.json'), JSON.stringify(catalog,null,2)+'\n');
await fs.writeFile(path.join(root,'electron/theme-catalog.json'),JSON.stringify(catalog.map(t=>({id:t.id,mode:t.mode,background:t.tokens['--bg'],widgetBackground:t.tokens['--widget-bg']})),null,2)+'\n');
console.log(`Prepared ${catalog.length} scoped runtime themes`);
